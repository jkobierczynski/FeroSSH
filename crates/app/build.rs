//! Embeds the application manifest (per-monitor DPI v2, Windows 10+), a
//! version resource (the Details tab of the exe's Properties, which code
//! signing checks against) and the FeroSSH icon, and makes Windows load the DLLs the exe imports
//! from System32 only, so a DLL planted next to a downloaded ferossh.exe is
//! never picked up.
//!
//! The DLLs only the window uses are delay-loaded: Windows loads each on
//! the first call into it. The sandboxed worker and viewer, the same exe,
//! never call them, so they never load user32 or anything that pulls it
//! in, and can run with Win32k lockdown (see sandbox.rs). The exe is also
//! marked compatible with CET shadow stacks; Control Flow Guard is a
//! rustc flag (.cargo/config.toml).

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=ferossh.manifest");
    println!("cargo:rerun-if-changed=ferossh.ico");
    let windows = std::env::var("CARGO_CFG_TARGET_OS").is_ok_and(|os| os == "windows");
    let msvc = std::env::var("CARGO_CFG_TARGET_ENV").is_ok_and(|env| env == "msvc");
    if windows && msvc {
        let dir = std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default();
        let manifest = std::path::Path::new(&dir).join("ferossh.manifest");
        println!("cargo:rustc-link-arg-bins=/MANIFEST:EMBED");
        println!(
            "cargo:rustc-link-arg-bins=/MANIFESTINPUT:{}",
            manifest.display()
        );
        // LOAD_LIBRARY_SEARCH_SYSTEM32, for the import table (Windows 10
        // 1607 and later; older versions ignore it).
        println!("cargo:rustc-link-arg-bins=/DEPENDENTLOADFLAG:0x800");
        for dll in DELAY_LOADED {
            println!("cargo:rustc-link-arg-bins=/DELAYLOAD:{dll}");
        }
        println!("cargo:rustc-link-arg-bins=delayimp.lib");
        // A DLL on the list that the exe ends up not importing is not an
        // error (LNK4199), just a note.
        println!("cargo:rustc-link-arg-bins=/IGNORE:4199");
        println!("cargo:rustc-link-arg-bins=/CETCOMPAT");

        // link.exe takes a compiled .res file as an input of its own, so
        // the resources are written here byte for byte: no rc.exe, and the
        // same bytes on every machine.
        let out = std::env::var("OUT_DIR").unwrap_or_default();
        let res = std::path::Path::new(&out).join("ferossh.res");
        let version = env!("CARGO_PKG_VERSION");
        let number = [
            env!("CARGO_PKG_VERSION_MAJOR"),
            env!("CARGO_PKG_VERSION_MINOR"),
            env!("CARGO_PKG_VERSION_PATCH"),
        ]
        .map(|n| n.parse::<u16>().unwrap_or(0));
        let strings = [
            ("CompanyName", "FeroSSH contributors"),
            ("FileDescription", "FeroSSH"),
            ("FileVersion", version),
            ("InternalName", "ferossh"),
            (
                "LegalCopyright",
                "Copyright (c) FeroSSH contributors. MIT OR Apache-2.0.",
            ),
            ("OriginalFilename", "ferossh.exe"),
            ("ProductName", "FeroSSH"),
            ("ProductVersion", version),
        ];
        let mut bytes = version_res([number[0], number[1], number[2], 0], &strings);
        // The icon is regenerated by scripts/make-icon.py from docs/logo.svg.
        let ico = std::fs::read(std::path::Path::new(&dir).join("ferossh.ico"));
        match ico.as_deref().map(icon_res) {
            Ok(Some(icon)) => bytes.extend(icon),
            _ => println!("cargo:warning=ferossh.ico missing or malformed; no exe icon"),
        }
        if std::fs::write(&res, bytes).is_ok() {
            println!("cargo:rustc-link-arg-bins={}", res.display());
        }
    }
}

/// The DLLs the window uses that load user32 or need Win32k themselves.
/// The rest of the import table (kernel32, ntdll, advapi32, ws2_32, the
/// crypto and API-set DLLs) is what the worker runs on. Delay-loading a
/// DLL makes no difference to the window apart from when it loads.
const DELAY_LOADED: &[&str] = &[
    "user32.dll",
    "gdi32.dll",
    "imm32.dll",
    "comctl32.dll",
    "comdlg32.dll",
    "shell32.dll",
    "ole32.dll",
    "oleaut32.dll",
    "shcore.dll",
    "uxtheme.dll",
    "dwmapi.dll",
    "d2d1.dll",
    "dwrite.dll",
    "winhttp.dll",
    "webauthn.dll",
    "userenv.dll",
    "crypt32.dll",
];

/// A .res file holding one RT_VERSION resource, laid out as rc.exe and
/// llvm-rc write it (llvm-rc gives the same bytes for the same input).
fn version_res(version: [u16; 4], strings: &[(&str, &str)]) -> Vec<u8> {
    let ms = (u32::from(version[0]) << 16) | u32::from(version[1]);
    let ls = (u32::from(version[2]) << 16) | u32::from(version[3]);
    // VS_FIXEDFILEINFO: signature, structure version, file and product
    // version, flags mask and flags, VOS_NT_WINDOWS32, VFT_APP, subtype,
    // date.
    let fixed: Vec<u8> = [
        0xFEEF_04BD,
        0x0001_0000,
        ms,
        ls,
        ms,
        ls,
        0x3F,
        0,
        0x0004_0004,
        1,
        0,
        0,
        0,
    ]
    .into_iter()
    .flat_map(u32::to_le_bytes)
    .collect();
    let strings: Vec<Vec<u8>> = strings
        .iter()
        .map(|(key, value)| {
            let value = utf16z(value);
            node(key, &value, (value.len() / 2) as u16, true, &[])
        })
        .collect();
    // US English, Unicode.
    let table = node("040904B0", &[], 0, true, &strings);
    let string_info = node("StringFileInfo", &[], 0, true, &[table]);
    let translation = node("Translation", &[0x09, 0x04, 0xB0, 0x04], 4, false, &[]);
    let var_info = node("VarFileInfo", &[], 0, true, &[translation]);
    let data = node(
        "VS_VERSION_INFO",
        &fixed,
        52,
        false,
        &[string_info, var_info],
    );

    // A .res file starts with an empty entry.
    let mut res = vec![
        0, 0, 0, 0, 0x20, 0, 0, 0, 0xFF, 0xFF, 0, 0, 0xFF, 0xFF, 0, 0,
    ];
    res.extend([0; 16]);
    // RT_VERSION, moveable and pure.
    resource(&mut res, 16, 1, 0x30, &data);
    res
}

/// The resources for a .ico file: each image as an RT_ICON (named 1, 2,
/// ...), then an RT_GROUP_ICON named 1 listing them, which is what
/// Explorer shows and LoadIcon(1) loads. A group entry is the .ico
/// directory entry with the image's resource name in place of its file
/// offset. None if the file is not an icon.
fn icon_res(ico: &[u8]) -> Option<Vec<u8>> {
    let u16_at = |i: usize| Some(u16::from_le_bytes(ico.get(i..i + 2)?.try_into().ok()?));
    let u32_at = |i: usize| Some(u32::from_le_bytes(ico.get(i..i + 4)?.try_into().ok()?));
    if u16_at(0)? != 0 || u16_at(2)? != 1 {
        return None;
    }
    let count = u16_at(4)?;
    let mut res = Vec::new();
    let mut group = ico.get(..6)?.to_vec();
    for n in 0..count {
        let entry = 6 + usize::from(n) * 16;
        let size = u32_at(entry + 8)? as usize;
        let offset = u32_at(entry + 12)? as usize;
        let image = ico.get(offset..offset.checked_add(size)?)?;
        // RT_ICON, moveable and discardable.
        resource(&mut res, 3, n + 1, 0x1010, image);
        group.extend(ico.get(entry..entry + 4)?);
        // A PNG image's planes may be 0 in the file; rc.exe writes 1.
        group.extend(u16_at(entry + 4)?.max(1).to_le_bytes());
        group.extend(ico.get(entry + 6..entry + 12)?);
        group.extend((n + 1).to_le_bytes());
    }
    // RT_GROUP_ICON, moveable, pure and discardable.
    resource(&mut res, 14, 1, 0x1030, &group);
    Some(res)
}

/// Appends one resource with a numeric type and name: data size, header
/// size, type, name, data version, memory flags, language 0x0409,
/// version, characteristics, then the data, 32-bit aligned.
fn resource(res: &mut Vec<u8>, kind: u16, name: u16, flags: u16, data: &[u8]) {
    res.extend((data.len() as u32).to_le_bytes());
    res.extend(0x20u32.to_le_bytes());
    res.extend([0xFF, 0xFF]);
    res.extend(kind.to_le_bytes());
    res.extend([0xFF, 0xFF]);
    res.extend(name.to_le_bytes());
    res.extend(0u32.to_le_bytes());
    res.extend(flags.to_le_bytes());
    res.extend([0x09, 0x04]);
    res.extend([0; 8]);
    res.extend(data);
    pad4(res);
}

/// One block of a version resource: length, value length, type (1 for
/// text), key, then its value and child blocks, each 32-bit aligned.
fn node(key: &str, value: &[u8], value_len: u16, text: bool, children: &[Vec<u8>]) -> Vec<u8> {
    // The length goes first; it is filled in once the block is complete.
    let mut v = vec![0, 0];
    v.extend(value_len.to_le_bytes());
    v.extend(u16::from(text).to_le_bytes());
    v.extend(utf16z(key));
    pad4(&mut v);
    v.extend(value);
    for child in children {
        pad4(&mut v);
        v.extend(child);
    }
    let len = (v.len() as u16).to_le_bytes();
    v.splice(..2, len);
    v
}

fn utf16z(s: &str) -> Vec<u8> {
    s.encode_utf16()
        .chain([0])
        .flat_map(u16::to_le_bytes)
        .collect()
}

fn pad4(v: &mut Vec<u8>) {
    while !v.len().is_multiple_of(4) {
        v.push(0);
    }
}
